CREATE TYPE full_name_type AS (
  first_name varchar(20),
  last_name varchar(20),
  patronymic varchar(20)
);

CREATE DOMAIN full_name_valid AS full_name_type
CHECK (
  ((VALUE).first_name IS NOT NULL AND length(trim((VALUE).first_name)) >= 3) AND
  ((VALUE).last_name IS NOT NULL AND length(trim((VALUE).last_name)) >= 3)
);

CREATE TYPE passport_type AS (
  passport_series smallint,
  passport_number integer,
  issued_by varchar(40),
  unit_code varchar(7),
  issue_date date,
  registration_address text
);

CREATE DOMAIN passport_valid AS passport_type
CHECK (
  ((VALUE).passport_series IS NOT NULL AND (VALUE).passport_series <= 9999) AND
  ((VALUE).passport_number IS NOT NULL AND (VALUE).passport_number <= 999999) AND
  ((VALUE).issued_by IS NOT NULL AND length(trim((VALUE).issued_by)) >= 5) AND
  ((VALUE).unit_code IS NOT NULL) AND
  ((VALUE).issue_date IS NOT NULL AND (VALUE).issue_date <= CURRENT_DATE) AND
  ((VALUE).registration_address IS NOT NULL AND length(trim((VALUE).registration_address)) >= 5)
);

CREATE TYPE address_type AS (
  index integer,
  country varchar(30),
  city varchar(20),
  street varchar(30),
  house integer,
  building integer
);

CREATE DOMAIN address_valid AS address_type
CHECK (
  ((VALUE).index IS NOT NULL AND (VALUE).index > 0 AND (VALUE).index <= 999999) AND
  ((VALUE).country IS NOT NULL AND length(trim((VALUE).country)) BETWEEN 2 AND 30) AND
  ((VALUE).city IS NOT NULL AND length(trim((VALUE).city)) BETWEEN 2 AND 20) AND
  ((VALUE).street IS NOT NULL AND length(trim((VALUE).street)) BETWEEN 2 AND 30) AND
  ((VALUE).house IS NOT NULL AND (VALUE).house > 0)
);

--Независимые справочники

CREATE TABLE IF NOT EXISTS contract_type (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(50) NOT NULL UNIQUE CONSTRAINT chk_contract_type_name_length CHECK (length(name) >= 2),
  description varchar(100) NOT NULL UNIQUE
);


CREATE TABLE IF NOT EXISTS construction_status (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(10) NOT NULL UNIQUE DEFAULT 'котлован' CONSTRAINT chk_construction_status_name_length CHECK (length(name) >= 3),
  number integer NOT NULL UNIQUE CONSTRAINT chk_construction_status_number_value CHECK (number > 0),
  is_available_for_sale boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE construction_status IS 'Справочник этапов готовности
объекта (котлован → стены → отделка → получено РВЭ → сдан).
Поле number задает порядок этапов.';


CREATE TABLE IF NOT EXISTS position (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(40) NOT NULL UNIQUE CONSTRAINT chk_position_name_length CHECK (length(name) > 5),
  salary integer NOT NULL CONSTRAINT chk_position_salary_value CHECK (salary >= 27093)
);


CREATE TABLE IF NOT EXISTS keys_type (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(10) NOT NULL UNIQUE CONSTRAINT chk_keys_type_name_length CHECK (length(name) >= 3),
  description varchar(100) NOT NULL UNIQUE 
);


CREATE TABLE IF NOT EXISTS real_estate_type (
