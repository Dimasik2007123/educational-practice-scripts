CREATE TABLE IF NOT EXISTS requirement (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(25) NOT NULL UNIQUE CONSTRAINT chk_requirement_name_length CHECK (length(name) >= 3),
  description varchar(100) NOT NULL UNIQUE
);


--Ключевые объекты

CREATE TABLE IF NOT EXISTS employee (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name full_name_valid NOT NULL,
  position_id integer NOT NULL,
  phone varchar(20) NOT NULL UNIQUE CONSTRAINT chk_employee_phone_digits_only CHECK (phone ~ '^[0-9]+$'),
  email varchar(30) NOT NULL UNIQUE CONSTRAINT chk_employee_email_contains_at CHECK (email LIKE '%@%'),
  hire_date date NOT NULL DEFAULT CURRENT_DATE CONSTRAINT chk_employee_hire_date_value CHECK (hire_date <= CURRENT_DATE)
);


CREATE TABLE IF NOT EXISTS client (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name full_name_valid NOT NULL,
  birth_date date NOT NULL CONSTRAINT chk_client_birth_date_value CHECK (birth_date <= CURRENT_DATE),
  phone varchar(20) NOT NULL UNIQUE CONSTRAINT chk_client_phone_digits_only CHECK (phone ~ '^[0-9]+$'),
  email varchar(30) UNIQUE CONSTRAINT chk_client_email_contains_at CHECK (email IS NULL OR email LIKE '%@%'),
  passport passport_valid NOT NULL UNIQUE
);


CREATE TABLE IF NOT EXISTS real_estate_object (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  real_estate_type_id integer NOT NULL,
  address address_valid NOT NULL UNIQUE,
  cadastral_number varchar(19) NOT NULL UNIQUE CONSTRAINT chk_real_estate_object_cadastral_number_value CHECK (cadastral_number ~ '^[0-9:]+$'),
  floor smallint NOT NULL CONSTRAINT chk_real_estate_object_floor_value CHECK (floor BETWEEN -1 AND 50),
  apartment_number integer NOT NULL CONSTRAINT chk_real_estate_object_apartment_number_value CHECK (apartment_number > 0),
  rooms_count smallint CONSTRAINT chk_real_estate_object_rooms_count_value CHECK (rooms_count IS NULL OR (rooms_count BETWEEN 1 AND 5)),
  total_area real NOT NULL CONSTRAINT chk_real_estate_object_total_area_value CHECK (total_area > 0),
  living_area real CONSTRAINT chk_real_estate_object_living_area_value CHECK (living_area IS NULL OR (living_area <= total_area)),
  construction_status_id integer NOT NULL,
  completion_date date NOT NULL,
  price numeric(10, 2) NOT NULL CONSTRAINT chk_real_estate_object_price_value CHECK (price > 0),
  real_estate_status_id integer NOT NULL
);


--Зависимые объекты

CREATE TABLE IF NOT EXISTS account (
  employee_id integer NOT NULL PRIMARY KEY,
  login varchar(20) NOT NULL UNIQUE CONSTRAINT chk_account_login_length CHECK (length(login) >= 5),
  password varchar(20) NOT NULL DEFAULT 'Qwerty123' CONSTRAINT chk_account_password_length CHECK (length(password) >= 9)
);


CREATE TABLE IF NOT EXISTS keys (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  real_estate_object_id integer NOT NULL,
  key_set_number integer NOT NULL UNIQUE CONSTRAINT chk_keys_key_set_number_value CHECK (key_set_number > 0),
  quantity integer NOT NULL DEFAULT 6 CONSTRAINT chk_keys_quantity_value CHECK (quantity BETWEEN 1 AND 10),
  issue_date date NOT NULL DEFAULT CURRENT_DATE CONSTRAINT chk_keys_issue_date_value CHECK (issue_date <= CURRENT_DATE),
  client_id integer NOT NULL,
  locker_code integer NOT NULL UNIQUE DEFAULT 100000 CONSTRAINT chk_keys_locker_code_value CHECK (locker_code BETWEEN 100000 AND 999999),
  keys_type_id integer NOT NULL
);
COMMENT ON TABLE keys IS 'Комплекты ключей от объектов
недвижимости. Один объект может иметь несколько
комплектов (входная дверь, подъезд, почтовый ящик).
Выдаются клиенту после подписания акта приема-передачи.
Код постамата (locker_code) используется для получения ключей через автоматический постамат.';


--Документы

CREATE TABLE IF NOT EXISTS sale (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP CONSTRAINT chk_sale_sale_date_value CHECK (sale_date <= CURRENT_TIMESTAMP),
  employee_id integer NOT NULL,
  client_id integer NOT NULL,
  contract_type_id integer NOT NULL,
  notes text
);


CREATE TABLE IF NOT EXISTS complaint (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filling_date date NOT NULL DEFAULT CURRENT_DATE CONSTRAINT chk_complaint_filling_date_value CHECK (filling_date <= CURRENT_DATE),
  sale_id integer NOT NULL UNIQUE,
  client_id integer NOT NULL,
  real_estate_object_id integer NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'новая'
);

CREATE TABLE IF NOT EXISTS booking (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_date date NOT NULL DEFAULT CURRENT_DATE,
  expiration_date date NOT NULL DEFAULT CURRENT_DATE + INTERVAL '14 days',
  client_id integer NOT NULL,
  employee_id integer NOT NULL,
  real_estate_object_id integer NOT NULL
);


--Промежуточные таблицы

CREATE TABLE IF NOT EXISTS sale_item (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id integer NOT NULL,
  real_estate_object_id integer NOT NULL UNIQUE,
  price numeric(10, 2) NOT NULL CONSTRAINT chk_sale_item_price_value CHECK (price > 0),
  line_number smallint NOT NULL CONSTRAINT chk_sale_item_line_number_value CHECK (line_number > 0)
);
COMMENT ON TABLE sale_item IS 'Позиция договора продажи.
Связывает продажу (шапку) с конкретным объектом недвижимости.
Одна продажа может содержать несколько позиций (например, квартира + машиноместо).';


CREATE TABLE IF NOT EXISTS complaint_item (
  complaint_id integer NOT NULL,
  requirement_id integer NOT NULL,
  description text NOT NULL,
  claim_amount numeric(10, 2) CONSTRAINT chk_complaint_item_claim_amount_value CHECK (claim_amount > 0),
  PRIMARY KEY (complaint_id, requirement_id)
);

