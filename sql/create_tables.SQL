  name varchar(25) NOT NULL UNIQUE CONSTRAINT chk_real_estate_type_name_length CHECK (length(name) >= 5), 
  description varchar(100) UNIQUE
);


CREATE TABLE IF NOT EXISTS real_estate_status (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(25) NOT NULL UNIQUE CONSTRAINT chk_real_estate_status_name_length CHECK (length(name) >= 2),
  description varchar(100) NOT NULL UNIQUE
